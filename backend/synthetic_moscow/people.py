def translit(text: str) -> str:
    return "".join(TRANSLIT.get(char, char) for char in text.lower())


def feminine(surname: str) -> str:
    for suffix, replacement in (("ский", "ская"), ("цкий", "цкая"), ("ой", "ая")):
        if surname.endswith(suffix):
            return surname[: -len(suffix)] + replacement
    if surname.endswith(("ов", "ев", "ёв", "ин")):
        return surname + "а"
    # -енко, -ук, -их, -ых and similar surnames do not change.
    return surname


@dataclass(frozen=True)
class Person:
    name: str
    lastname: str
    surname: str
    username: str

    @property
    def full_name(self) -> str:
        return f"{self.surname} {self.name} {self.lastname}"

    @property
    def short_name(self) -> str:
        return f"{self.surname} {self.name[0]}. {self.lastname[0]}."


class PeopleFactory:
    """Distinct people for one package: no repeated full name or login."""

    def __init__(self, rng: random.Random):
        self.rng = rng
        self.full_names: set[tuple[str, str, str]] = set()
        self.usernames: set[str] = set()
        self.surnames: set[str] = set()

    def _login(self, surname: str, name: str, lastname: str) -> str:
        base = f"{translit(surname)}.{translit(name)[0]}{translit(lastname)[0]}"
        login, suffix = base, 1
        while login in self.usernames:
            suffix += 1
            login = f"{base}{suffix}"
        self.usernames.add(login)
        return login

    def person(self, *, female: bool = False, distinct_surname: bool = False) -> Person:
        while True:
            tatar = not female and self.rng.random() < 0.12
            first = self.rng.choice(TATAR_MALE_NAMES if tatar else MALE_NAMES)
            father = self.rng.choice(TATAR_MALE_NAMES if tatar else MALE_NAMES)
            surname = self.rng.choice(TATAR_SURNAMES if tatar else SURNAMES)
            if female:
                name, lastname, surname = (
                    self.rng.choice(FEMALE_NAMES),
                    father[2],
                    feminine(surname),
                )
            else:
                name, lastname = first[0], father[1]
            key = (surname, name, lastname)
            if key in self.full_names or (distinct_surname and surname in self.surnames):
                continue
            self.full_names.add(key)
            self.surnames.add(surname)
            return Person(name, lastname, surname, self._login(surname, name, lastname))
